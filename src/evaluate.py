"""Display held-out evaluation metrics produced by `python -m src.train`.

This script deliberately does not retrain the model or modify predictions.
It reads outputs/metrics.json generated by the existing training pipeline.
"""
from pathlib import Path
import json


PROJECT_ROOT = Path(__file__).resolve().parents[1]
METRICS_PATH = PROJECT_ROOT / "outputs" / "metrics.json"


def main():
    if not METRICS_PATH.exists():
        raise FileNotFoundError(
            "Evaluation metrics not found. Run `python -m src.train` first."
        )

    results = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    print("Held-out test evaluation")
    print(f"Rows: {results['test_rows']}")
    print(f"Validation-selected threshold: "
          f"{results['threshold_selected_on_validation']:.6f}")

    for model_name in ("baseline", "logistic_regression"):
        metrics = results[model_name]
        print(f"\\n{model_name.replace('_', ' ').title()}")
        for metric in ("accuracy", "precision", "recall", "f1",
                       "roc_auc", "pr_auc"):
            print(f"  {metric}: {metrics[metric]:.4f}")
        print(f"  confusion_matrix: {metrics['confusion_matrix']}")


if __name__ == "__main__":
    main()
